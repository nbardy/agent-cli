// One registry, catalog.jsonc. Keep parser effort recognition in sync without runtime file I/O.
import { readFile, writeFile } from 'node:fs/promises';
const source = new URL('../catalog.jsonc', import.meta.url);
const raw = JSON.parse((await readFile(source, 'utf8')).replace(/^\s*\/\/.*$/gm, ''));
const providers = raw.providers.map(p => ({id:p.id, dynamic:p.supportsDynamicModels, aliases:p.aliases ?? {}, models:p.models.map(m => ({id:m.id, reasoning:m.reasoning ?? null}))}));
const text = `// Generated by scripts/gen-model-catalog.mjs from catalog.jsonc; do not edit.\nexport const MODEL_CATALOG = ${JSON.stringify(providers, null, 2)};\n`;
const target = new URL('../src/model-catalog.generated.ts', import.meta.url);
if (process.argv.includes('--check')) {
  if (await readFile(target, 'utf8') !== text) throw Error('Stale model catalog: run pnpm gen:catalog');
} else await writeFile(target, text);
